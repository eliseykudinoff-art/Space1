class MCPToolClient:
    """Model Context Protocol (MCP) Client for execution."""

    def execute_tool(self, tool_name: str, params: Dict[str, Any]) -> Dict[str, Any]:
        """Call external CLI tools or sandbox environments via MCP protocol."""
        import subprocess
        import json

        cli_tools = {
            "python": ["python", "-c"],
            "bash": ["bash", "-c"],
            "python3": ["python3", "-c"],
            "sh": ["sh", "-c"],
        }

        command = params.get("command", params.get("code", params.get("input", "")))

        if tool_name in cli_tools:
            try:
                base_cmd = cli_tools[tool_name]
                result = subprocess.run(
                    base_cmd + [command],
                    capture_output=True,
                    text=True,
                    timeout=30,
                    cwd=params.get("cwd", None)
                )
                return {
                    "success": result.returncode == 0,
                    "tool": tool_name,
                    "output": result.stdout if result.returncode == 0 else result.stderr,
                    "returncode": result.returncode
                }
            except subprocess.TimeoutExpired:
                return {
                    "success": False,
                    "tool": tool_name,
                    "output": "Execution timed out after 30 seconds."
                }
            except Exception as e:
                return {
                    "success": False,
                    "tool": tool_name,
                    "output": str(e)
                }

        return {
            "success": False,
            "tool": tool_name,
            "output": f"Unknown tool '{tool_name}'. Supported: {list(cli_tools.keys())}. "
                      f"Received params: {json.dumps(params, default=str)[:200]}"
        }

