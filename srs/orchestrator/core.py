def calculate_token_cost(model_name: str, tokens_used: int) -> float:
    """Calculate cost of tokens based on config prices or a safe fallback rate."""
    cfg = get_config()
    # Try to find model in prices
    price_info = None
    for provider_key in ["openai", "anthropic", "ollama"]:
        provider_prices = getattr(cfg.prices, provider_key, {})
        if model_name in provider_prices:
            price_info = provider_prices[model_name]
            break
            
    if price_info is not None:
        rate = getattr(price_info, "output", 0.002)
        return (tokens_used * rate) / 1000.0
        
    return (tokens_used * 0.002) / 1000.0


def parse_response_content(text: str) -> Dict[str, Any]:
    """Parse and extract structured code blocks and JSON from LLM text."""
    import re
    import json
    result = {"raw_text": text, "extracted_code": None, "extracted_json": None}
    
    # 1. Extract markdown code blocks
    code_blocks = re.findall(r"```(?:python)?\n(.*?)\n```", text, re.DOTALL)
    if code_blocks:
        result["extracted_code"] = code_blocks[0].strip()
        
    # 2. Extract JSON blocks
    json_blocks = re.findall(r"```json\n(.*?)\n```", text, re.DOTALL)
    if json_blocks:
        try:
            result["extracted_json"] = json.loads(json_blocks[0].strip())
        except Exception as e:
            import logging
            logging.getLogger(__name__).warning(f"Suppressed error: {e}")
            
    # Fallback to general JSON extraction if curly braces are present
    if not result["extracted_json"]:
        curly_blocks = re.findall(r"({.*?})", text, re.DOTALL)
        for b in curly_blocks:
            try:
                result["extracted_json"] = json.loads(b.strip())
                break
            except (json.JSONDecodeError, ValueError):
                pass
                
    return result


class CircuitBreakerOpenException(Exception):
    """Exception raised when circuit breaker is in OPEN state."""
    pass


class CircuitBreaker:
    """
    Circuit Breaker per 10_SECURITY.md §III.2.

    Extends classic API fault-tolerance with:
      - theta_fail: failure rate threshold in sliding window
      - kappa: budget overrun multiplier (C_actual > kappa * C_predicted)
      - d_max: maximum cascade depth
      - Integration with H / PlatformRiskScore for global trip
    """
    def __init__(
        self,
        failure_threshold: int = 3,
        cooldown_seconds: float = 2.0,
        theta_fail: float = 0.5,
        window_size: int = 10,
        kappa: float = 2.0,
        d_max: int = 5,
        consecutive_successes_threshold: int = 3,
    ):
        self.failure_threshold = failure_threshold
        self.cooldown_seconds = cooldown_seconds
        self.theta_fail = theta_fail          # max failure ratio in window
        self.window_size = window_size        # sliding window size
        self.kappa = kappa                    # budget overrun multiplier
        self.d_max = d_max                    # max cascade depth
        self.consecutive_successes_threshold = consecutive_successes_threshold

        self.state = "CLOSED"
        self.failure_count = 0
        self.success_count = 0

        self.last_failure_time = None
        self._failures_window = []            # timestamps
        self._budget_violations = 0
        self._cascade_depth = 0
        self._global_risk = 0.0

    def before_call(self, H=None, platform_risk=None):
        """Check state before execution. Integrates H and PlatformRiskScore for global trip."""
        # Global trip: if H is CRITICAL or platform_risk is high, force OPEN
        if H is not None and H < 0.2:
            self.state = "OPEN"
            self._global_risk = 1.0
        if platform_risk is not None and platform_risk > 0.8:
            self.state = "OPEN"
            self._global_risk = max(self._global_risk, platform_risk)

        if self.state == "OPEN":
            if self.last_failure_time and (datetime.now() - self.last_failure_time).total_seconds() > self.cooldown_seconds:
                self.state = "HALF_OPEN"
                self.consecutive_successes = 0  # Reset when entering HALF_OPEN
            else:
                raise CircuitBreakerOpenException("Circuit Breaker is OPEN. Execution blocked.")

    def record_success(self):
        """Record success. In HALF_OPEN, need consecutive successes to close."""
        self.failure_count = 0  # Reset on success
        self.success_count += 1
        self._cascade_depth = max(0, self._cascade_depth - 1)
        self._budget_violations = 0  # Also reset budget violations

        if self.state == "HALF_OPEN":
            self.consecutive_successes += 1
            if self.consecutive_successes >= self.consecutive_successes_threshold:
                self.state = "CLOSED"
                self.consecutive_successes = 0
        else:
            self.state = "CLOSED"
            self.consecutive_successes = 0

    def record_failure(self, cost_actual=None, cost_predicted=None):
        """Record failure with optional budget overrun check."""
        now = datetime.now().timestamp()
        # Trim window BEFORE adding new failure for accurate ratio calculation
        cutoff = now - 60.0  # 1-minute sliding window
        self._failures_window = [t for t in self._failures_window if t > cutoff]
        
        # Check theta_fail threshold BEFORE adding to window
        total_recent = self.success_count + len(self._failures_window)
        self._failures_window.append(now)  # Add after ratio check
        
        if total_recent > 0 and len(self._failures_window) / total_recent > self.theta_fail:
            self.state = "OPEN"

        # Check kappa budget overrun
        if cost_actual is not None and cost_predicted is not None and cost_predicted > 0:
            if cost_actual > self.kappa * cost_predicted:
                self._budget_violations += 1
                if self._budget_violations >= 2:
                    self.state = "OPEN"

        # Check cascade depth
        self._cascade_depth += 1
        if self._cascade_depth >= self.d_max:
            self.state = "OPEN"

        self.failure_count += 1
        self.last_failure_time = datetime.now()

        if self.state == "CLOSED" and self.failure_count >= self.failure_threshold:
            self.state = "OPEN"
        elif self.state == "HALF_OPEN":
            self.state = "OPEN"


def _run_async(coro, timeout: float = 10.0):
    """
    Execute an async coroutine safely.

    FIX: Убран thread-bomb (run_coroutine_threadsafe). 
    Если уже в async контексте — await напрямую через nest_asyncio.
    Если нет — asyncio.run с таймаутом.
    """
    import asyncio
    try:
        loop = asyncio.get_running_loop()
        # Already in an async context — use nest_asyncio if available
        try:
            import nest_asyncio
            nest_asyncio.apply()
            return loop.run_until_complete(asyncio.wait_for(coro, timeout=timeout))
        except ImportError:
            # Fallback: create new thread with own loop
            import concurrent.futures
            with concurrent.futures.ThreadPoolExecutor(max_workers=1) as executor:
                future = executor.submit(asyncio.run, asyncio.wait_for(coro, timeout=timeout))
                return future.result(timeout=timeout + 5)
    except RuntimeError:
        # No running loop — use asyncio.run with timeout
        return asyncio.run(asyncio.wait_for(coro, timeout=timeout))


