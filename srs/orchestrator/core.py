def select_executor(
    action: Action, 
    candidates: list[ExecutorProfile], 
    history: ExecutorStatsRegistry,
    tool_manager: AIOSToolManager | None = None
) -> ExecutorProfile:
    """
    Select appropriate specialist executor using UCB1 per 03_PIPELINE_MATH.md §VII.1.
    Raises NoEligibleExecutorError if trust limits are violated.
    """
    import math
    
    trust_min = 0.3
    eligible = [c for c in candidates if c.trust_score >= trust_min]
    if not eligible:
        raise NoEligibleExecutorError("No executor satisfies minimum trust requirements.")
    
    # If tool_manager is provided, use its UCB1 implementation
    if tool_manager is not None:
        candidate_names = [c.name for c in eligible]
        selected_name = tool_manager.select_best_specialist(candidate_names)
        # Find the corresponding ExecutorProfile
        for c in eligible:
            if c.name == selected_name:
                return c
    
    # Fallback: UCB1 implementation for cold-start
    # UCB1 = mean_reward + c * sqrt(ln(N) / n_i)
    # For cold start (n_i = 0), guarantee first selection
    c_exploration = 1.414  # sqrt(2)
    
    # Get UCB1 stats from history or use trust_score as prior reward
    best_score = -float('inf')
    best_candidate = eligible[0]
    
    for c in eligible:
        # Get historical stats
        stats = history.data.get(c.name, {"selections": 0, "rewards_sum": 0.0})
        n_i = stats.get("selections", 0)
        
        # Cold start: unselected specialist gets immediate selection
        if n_i == 0:
            return c
        
        # UCB1 formula
        mean_reward = stats.get("rewards_sum", 0.0) / n_i
        total_selections = sum(history.data.get(other.name, {"selections": 0}).get("selections", 0) for other in eligible)
        ucb_score = mean_reward + c_exploration * math.sqrt(math.log(max(1, total_selections)) / n_i)
        
        if ucb_score > best_score:
            best_score = ucb_score
            best_candidate = c
    
    return best_candidate


