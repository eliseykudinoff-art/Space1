def predict_estimates(
    x: CapabilityVector, 
    category_probs: dict[str, float], 
    price: float,
    n_completed: int = 0,
    agent_history: list | None = None,
) -> tuple[float, float, float]:
    """Predicts (phi_hat, q_predicted_hat, psi_hat) — 03_PIPELINE_MATH.md §III.1."""
    import math
    
    # x is dict[str, float] — extract values
    x_values = list(x.values()) if isinstance(x, dict) else x if isinstance(x, (list, tuple)) else []
    x_avg = sum(x_values) / len(x_values) if x_values else 0.5
    x_avg = max(0.0, min(1.0, x_avg))
    
    category_factor = category_probs.get("code", 0.5) * 0.8 + 0.2
    price_norm = min(price / 500.0, 1.0)
    
    v_ref_phi = 0.3 + 0.5 * x_avg + 0.2 * price_norm
    v_ref_q = 0.4 + 0.5 * x_avg
    v_ref_psi = 0.1 + 0.3 * (1.0 - x_avg) + 0.1 * (1.0 - category_factor)
    
    if agent_history and len(agent_history) > 0:
        prior_q, prior_psi = 0.5, 0.15
        n = len(agent_history)
        observed_q = sum(h.get("quality", prior_q) for h in agent_history) / n
        observed_psi = sum(h.get("risk", prior_psi) for h in agent_history) / n
        alpha = n / (n + 3)
        v_bayes_q = alpha * observed_q + (1 - alpha) * prior_q
        v_bayes_psi = alpha * observed_psi + (1 - alpha) * prior_psi
        v_bayes_phi = 0.3 + 0.4 * alpha + 0.3 * price_norm
    else:
        v_bayes_q = 0.5
        v_bayes_psi = 0.15
        v_bayes_phi = 0.3 + 0.2 * price_norm
    
    confidence = sum(1.0 for xi in x_values if xi > 0.6) / len(x_values) if x_values else 0.5
    v_llm_q = 0.5 + 0.4 * confidence
    v_llm_psi = 0.1 + 0.2 * (1.0 - confidence)
    v_llm_phi = 0.4 + 0.3 * confidence + 0.3 * price_norm
    
    # Ensemble weights by n_completed
    if n_completed < 5:
        w = [0.4, 0.2, 0.4]
    elif n_completed < 20:
        w = [0.2, 0.5, 0.3]
    else:
        w = [0.1, 0.7, 0.2]
    
    phi_hat = w[0] * v_ref_phi + w[1] * v_bayes_phi + w[2] * v_llm_phi
    q_predicted_hat = w[0] * v_ref_q + w[1] * v_bayes_q + w[2] * v_llm_q
    psi_hat = w[0] * v_ref_psi + w[1] * v_bayes_psi + w[2] * v_llm_psi
    
    phi_hat = max(0.0, min(1.0, phi_hat))
    q_predicted_hat = max(0.0, min(1.0, q_predicted_hat))
    psi_hat = max(0.0, min(1.0, psi_hat))
    
    return phi_hat, q_predicted_hat, psi_hat
