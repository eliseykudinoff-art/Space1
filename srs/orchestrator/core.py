class SignalToContextSynthesizer:
    """
    Signal-to-Context Synthesizer (G10 / G2).
    
    Transforms the homeostatic pressures (signals) and memory history
    into a structured OrchestratorContext (Prompt / Task Guide) for LLM decision making.
    
    Formula:
        Chain/Context = f(Impulse, Memory, Context)
    """
    
    def __init__(self, memory: Optional[EpisodicMemory] = None):
        self.memory = memory or EpisodicMemory()
        
    def synthesize(
        self,
        metrics: Dict[str, float],
        task: Any = None,
        regulator: Optional[HomeostaticRegulator] = None,
    ) -> OrchestratorContext:
        """
        Synthesize the active homeostatic signals and long-term memory into structured guide.
        
        Args:
            metrics: Active agent metrics (balance, success_rate, stress_level, etc.)
            task: Current candidate task (optional)
            regulator: HomeostaticRegulator instance to compute pressures (optional)
            
        Returns:
            OrchestratorContext containing structured prompts and variables.
        """
        regulator = regulator or HomeostaticRegulator()
        
        # 1. Calculate homeostatic pressures
        pressures = regulator.update_all(metrics)
        
        # 2. Get urgent variables (sorted descending by pressure signal)
        sorted_pressures = sorted(pressures.items(), key=lambda x: x[1], reverse=True)
        urgent = [k for k, v in sorted_pressures if v > 0.0]
        if not urgent:
            urgent = ["optimal_equilibrium"]
            
        # 3. Retrieve relevant lessons from strategic memory matching the top pressure keyword
        memories = []
        if urgent and urgent[0] != "optimal_equilibrium":
            memories = self.memory.recall_strategies(urgent[0])
            if not memories:
                # Try fallback on general tag
                memories = self.memory.recall_strategies("default")
                
        # 4. Classify active situation profile
        mode = regulator.get_mode()
        situation = f"Mode: {mode.upper()} | Critical drives: {', '.join(urgent[:3])}"
        
        # 5. Classify tone and recommended action guidelines
        if mode == "survival":
            tone = "CONSERVATIVE / SURVIVAL ONLY"
            guidelines = "Minimize tool cost. Focus purely on task completion. Reject speculative ideas."
        elif mode == "growth":
            tone = "EXPLORATIVE / LEARNING OR REPUTATION"
            guidelines = "Invest in long-term reputation and knowledge acquisition. Budget constraints relaxed."
        else:
            tone = "BALANCED / STEADY STATE"
            guidelines = "Maintain normal operations. Calibrate costs against time and expected quality."
            
        # 6. Build the prompt
        task_title = getattr(task, "title", "None") if task else "None"
        prompt = (
            f"=== ORCHESTRATOR INSTRUCTIONS ===\n"
            f"Active Situation: {situation}\n"
            f"Recommended Tone: {tone}\n"
            f"Guidelines: {guidelines}\n"
            f"Target Task: {task_title}\n"
            f"Top Pressures: {', '.join(f'{k}={v:.2f}' for k, v in sorted_pressures[:3])}\n"
        )
        if memories:
            prompt += f"Relevant Strategic Memories:\n" + "\n".join(f"- {m}" for m in memories[:3]) + "\n"
        prompt += "================================="
        
        return OrchestratorContext(
            prompt=prompt,
            situation=situation,
            recommended_tone=tone,
            priority_variables=urgent,
            pressures=pressures,
            relevant_history=memories,
        )


class HomeostaticUtilityModulator:
    """
    Homeostatic Utility Modulator (G10 / G19).
    
    Formula:
        U_final = U_base * f(H_pressure)
        
    Yerkes-Dodson inspired modulation curve for base utility based on total stress pressure:
    - Low pressure (total_pressure < 0.5): f = 0.5 + 0.5 * total_pressure (complacency / under-utilized)
    - Optimal zone (0.5 <= total_pressure < 1.0): f = 1.0 (peak performance)
    - Stress zone (1.0 <= total_pressure < 2.0): f = 1.0 - 0.3 * (total_pressure - 1.0) (conservative)
    - Critical zone (total_pressure >= 2.0): f = 0.1 (minimal operations / safety priority only)
    """
    
    def modulate(self, base_utility: float, pressures: Dict[str, float]) -> float:
        """
        Modulate decision utility using current homeostatic pressure vectors.
        
        Args:
            base_utility: Raw utility score computed by decision equations
            pressures: Active homeostatic metric pressures
            
        Returns:
            Modulated utility score
        """
        total_pressure = sum(max(0.0, v) for v in pressures.values())
        
        # Yerkes-Dodson inspired scaling factor
        if total_pressure < 0.5:
            f = 0.5 + 1.0 * total_pressure
            f = min(1.0, f)
        elif total_pressure < 1.0:
            f = 1.0
        elif total_pressure < 2.0:
            f = 1.0 - 0.3 * (total_pressure - 1.0)
            f = max(0.2, f)
        else:
            f = 0.1
            
        return base_utility * f


class WeightCalibrator:
    """
    Weight Calibrator (G19).
    
    A cybernetic adaptive weight calibrator. Uses homeostatic pressures
    to dynamically adjust the objective weights (profit, reputation, evolution, quality)
    towards equilibrium thresholds.
    """
    
    def __init__(self, base_weights: Optional[Dict[str, float]] = None):
        self.base_weights = base_weights or {
            "profit_weight": 0.30,
            "reputation_weight": 0.25,
            "evolution_weight": 0.20,
            "quality_weight": 0.25,
        }
        
    def calibrate(self, pressures: Dict[str, float]) -> Dict[str, float]:
        """
        Dynamically adjust base utility weights according to current pressures.
        
        Args:
            pressures: Active pressure signals (e.g. balance, success_rate, stress_level, knowledge)
            
        Returns:
            Calibrated and normalized weights dictionary.
        """
        calibrated = dict(self.base_weights)
        
        # Survival adjustments
        balance_p = pressures.get("balance", 0.0)
        success_p = pressures.get("success_rate", 0.0)
        stress_p = pressures.get("stress_level", 0.0)
        
        if balance_p > 0.3:
            # High balance pressure -> boost profit weight to earn money
            calibrated["profit_weight"] += balance_p * 0.5
            calibrated["evolution_weight"] = max(0.05, calibrated["evolution_weight"] - balance_p * 0.3)
            
        if success_p > 0.3 or stress_p > 0.3:
            # High stress or failure rate -> prioritize high quality & lower risk actions
            calibrated["quality_weight"] += max(success_p, stress_p) * 0.4
            calibrated["evolution_weight"] = max(0.05, calibrated["evolution_weight"] - 0.1)
            
        # Growth adjustments
        knowledge_p = pressures.get("knowledge", 0.0)
        reputation_p = pressures.get("reputation", 0.0)
        
        if knowledge_p > 0.3:
            calibrated["evolution_weight"] += knowledge_p * 0.4
            
        if reputation_p > 0.3:
            calibrated["reputation_weight"] += reputation_p * 0.4
            
        # Ensure all adjusted weights are positive and normalize to sum to 1.0
        for k in calibrated:
            calibrated[k] = max(0.01, calibrated[k])
            
        total = sum(calibrated.values())
        if total > 0.0:
            calibrated = {k: v / total for k, v in calibrated.items()}
            
        return calibrated


